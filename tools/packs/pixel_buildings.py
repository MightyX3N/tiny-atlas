"""Building textures for the default (pixel-art) pack: the city pack's CC0 building textures (ambientCG, see
packs/tinyatlas_pack_city/SOURCES.md) brought down to the default pack's pixel size (32 px for 3.3 m, about 9.7 px a
metre) and a few colours, so atlas/bne_buildings.lua's buildings look like the rest of the pixel world. They stay grey;
each building's colour tints them (brick keeps its own). Writes materials/.../default/bld/ and lua/.../default_bld.lua.
usage: python3 pixel_buildings.py <city pack folder> <default pack folder>"""
import os, sys
import numpy as np
from PIL import Image, ImageFilter, ImageOps

PX_PER_M = 32 / 3.3
# metres one texture repeat covers on a wall or roof (atlas/bne_buildings.lua's MATERIALS), and colours to keep
TEX = {"bld_plaster": (2.5, 5), "bld_brick": (1.4, 5), "bld_concrete": (2.4, 4), "bld_wood": (3.0, 5),
       "bld_metal": (2.0, 4), "bld_stone": (2.0, 5), "bld_glass": (6.0, 5), "bld_roof_tiles": (2.4, 5),
       "bld_roof_slate": (2.4, 4), "bld_roof_flat": (4.0, 4), "bld_plain": (1.0, 1)}

city, default = sys.argv[1], sys.argv[2]
src = os.path.join(city, "materials/tinyatlas/packs/city/bld")
dst = os.path.join(default, "materials/tinyatlas/packs/default/bld")
os.makedirs(dst, exist_ok=True)
lines = ["-- Generated by tools/packs/pixel_buildings.py - do not edit. Building textures (ambientCG, CC0) at the pack's",
         "-- pixel size, for atlas/bne_buildings.lua.", "return {", "  textures = {"]
for name, (metres, colours) in TEX.items():
    im = Image.open(os.path.join(src, name + ".png")).convert("RGB")
    side = max(8, 2 ** int(round(np.log2(metres * PX_PER_M))))
    small = im.resize((side, side), Image.LANCZOS)
    if colours > 1:
        # pixel art keeps its pattern readable: the brightness variation raised to a set amount (colours kept)
        a = np.array(small).astype(float)
        lum = a.mean(-1, keepdims=True)
        sd = float(lum.std())
        k = min(3.0, 16.0 / sd) if sd > 0.5 else 1.0
        a = lum.mean() + (lum - lum.mean()) * k + (a - lum)
        small = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
        small = small.quantize(colors=colours, method=Image.Quantize.MEDIANCUT).convert("RGB")
    small.save(os.path.join(dst, name + ".png"))
    lines.append('    %s = { file = "bld/%s.png" },' % (name, name))
    print("%s: %d px" % (name, side))
lines += ["  },", "}"]
open(os.path.join(default, "lua/tinyatlas/packs/default_bld.lua"), "w").write("\n".join(lines) + "\n")
