"""The worn strips along natural paths (atlas/cell.lua's worn_wood / worn_grass / worn_rural) for the default pixel pack:
the ground the strip lies on (forest floor, grass, open country) mixed pixel by pixel with the pack's bare earth, in
small clumps, so its green is exactly that ground's green. Seamless like the pack's tiles. Writes ground/worn_*.png and
lua/.../default_ground.lua.
usage: python3 worn_ground.py <default pack folder>"""
import os, sys
import numpy as np
from PIL import Image

pack = sys.argv[1]
g = os.path.join(pack, "materials/tinyatlas/packs/default/ground")
GROUNDS = {"wood": "forest_floor", "grass": "grass", "rural": "rural"}
lines = ["-- Generated by tools/packs/worn_ground.py - do not edit. Ground made from the pack's own tiles.", "return {", "  textures = {"]
for kind, base in GROUNDS.items():
    ground = np.array(Image.open(os.path.join(g, base + "_1.png")).convert("RGB")).astype(int)
    dirt = np.array(Image.open(os.path.join(g, "dirt_1.png")).convert("RGB")).astype(int)
    n = ground.shape[0]
    rng = np.random.default_rng(31)
    # clumps: a coarse random field (2 px cells, wrapped so the tile stays seamless), smoothed once
    field = np.kron(rng.random((n // 2, n // 2)), np.ones((2, 2)))
    field = (field + np.roll(field, 1, 0) + np.roll(field, -1, 0) + np.roll(field, 1, 1) + np.roll(field, -1, 1)) / 5
    mask = field < np.quantile(field, 0.3)                 # a third bare earth
    out = np.where(mask[:, :, None], dirt, ground)
    name = "worn_%s.png" % kind
    Image.fromarray(out.astype(np.uint8)).save(os.path.join(g, name))
    lines.append('    worn_%s = { file = "ground/%s" },' % (kind, name))
lines.append('    worn = { file = "ground/worn_grass.png" },')
lines += ["  },", "}"]
open(os.path.join(pack, "lua/tinyatlas/packs/default_ground.lua"), "w").write("\n".join(lines) + "\n")
for f in ("worn_1.png", "worn_2.png", "worn_3.png", "worn_4.png"):
    p = os.path.join(g, f)
    if os.path.exists(p): os.remove(p)
print("worn ground:", ", ".join("worn_" + k for k in GROUNDS))
